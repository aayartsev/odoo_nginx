#!/usr/bin/env bash
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd "$(dirname "$0")" && pwd)/lib/common.sh"

PURGE_CERTS=0

usage() {
  cat <<EOF
Usage: $(basename "$0") [--purge-certs]

Сброс к bootstrap: удаляет сгенерированные conf.d/<domain>.conf,
оставляет 00-*.conf и статическую страницу html/.

  --purge-certs   также удалить сертификаты в certbot/conf
                  (потребует подтверждения; учитывайте лимиты Let's Encrypt)
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help)
      usage
      exit 0
      ;;
    --purge-certs)
      PURGE_CERTS=1
      shift
      ;;
    *)
      echo "Неизвестный аргумент: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

echo "Сброс к bootstrap..."

removed=0
shopt -s nullglob
for conf in "${CONF_D}"/*.conf; do
  base="$(basename "$conf")"
  [[ "$base" == 00-*.conf ]] && continue
  if head -n 1 "$conf" | grep -q 'GENERATED by generate-sites.sh'; then
    echo "  удаляю ${base}"
    rm -f "$conf"
    removed=$((removed + 1))
  else
    echo "  пропуск (не GENERATED): ${base}"
  fi
done
shopt -u nullglob

if [[ "$removed" -eq 0 ]]; then
  echo "  сгенерированных конфигов не найдено"
fi

if [[ "$PURGE_CERTS" -eq 1 ]]; then
  echo
  read -r -p "Удалить сертификаты в certbot/conf? [y/N] " ans
  if [[ "${ans}" =~ ^[Yy]$ ]]; then
    # Сохраняем только .gitkeep в подкаталогах, очищаем live/archive/renewal
    for sub in live archive renewal accounts; do
      dir="${ROOT}/certbot/conf/${sub}"
      if [[ -d "$dir" ]]; then
        find "$dir" -mindepth 1 -maxdepth 1 ! -name '.gitkeep' -exec rm -rf {} +
        echo "  очищен certbot/conf/${sub}"
      fi
    done
  else
    echo "  сертификаты не тронуты"
  fi
fi

nginx_reload_if_running
echo "Готово: активен bootstrap (html/index.html)."
