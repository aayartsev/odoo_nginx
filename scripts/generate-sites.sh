#!/usr/bin/env bash
set -euo pipefail

# shellcheck source=lib/common.sh
source "$(cd "$(dirname "$0")" && pwd)/lib/common.sh"

load_env

SITES_LIST="${1:-${DEFAULT_SITES_LIST}}"
KEEP_DOMAINS=()

generate_one() {
  local domain="$1"
  local email="$2"
  local upstream="$3"
  local http_port="$4"
  local chat_port="$5"
  local template dest mode

  export DOMAIN="$domain"
  export UPSTREAM="$upstream"
  export HTTP_PORT="$http_port"
  export CHAT_PORT="$chat_port"

  if has_certificate "$domain"; then
    template="${TEMPLATES}/odoo-site.https.conf.tpl"
    mode="https"
  else
    template="${TEMPLATES}/odoo-site.http.conf.tpl"
    mode="http"
  fi

  dest="${CONF_D}/${domain}.conf"
  render_template "$template" "$dest"
  KEEP_DOMAINS+=("$domain")
  echo "  ${domain}.conf (${mode}) → ${upstream}:${http_port}/${chat_port}"
}

remove_stale_generated() {
  local conf base keep found
  shopt -s nullglob
  for conf in "${CONF_D}"/*.conf; do
    base="$(basename "$conf")"
    [[ "$base" == 00-bootstrap.conf ]] && continue
    if ! head -n 1 "$conf" | grep -q 'GENERATED by generate-sites.sh'; then
      continue
    fi
    found=0
    for keep in "${KEEP_DOMAINS[@]+"${KEEP_DOMAINS[@]}"}"; do
      if [[ "$base" == "${keep}.conf" ]]; then
        found=1
        break
      fi
    done
    if [[ "$found" -eq 0 ]]; then
      echo "  удаляю устаревший ${base}"
      rm -f "$conf"
    fi
  done
  shopt -u nullglob
}

usage() {
  cat <<EOF
Usage: $(basename "$0") [sites.list]

Генерирует conf.d/<domain>.conf по списку сайтов.
Если сертификат есть — HTTPS-шаблон, иначе HTTP.
По умолчанию: ${DEFAULT_SITES_LIST}
EOF
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

echo "Генерация конфигов из ${SITES_LIST}..."
mkdir -p "$CONF_D"
iter_sites "$SITES_LIST" generate_one
remove_stale_generated
nginx_reload_if_running
echo "Готово."
